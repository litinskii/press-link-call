export type Locale = keyof typeof messages;
export type TranslationKey = keyof typeof messages.en;

export function translate(locale: Locale, key: TranslationKey, values: Record<string, string | number> = {}): string {
  const template: string = messages[locale][key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

const knownSupportMessages: Partial<Record<string, TranslationKey>> = {
  "Camera and microphone access requires a secure HTTPS connection.": "secureContextRequired",
  "Camera and microphone access is not available in this browser.": "mediaUnavailable",
  "Could not verify media support in this browser. Try the latest Chrome, Edge, or Safari.": "supportCheckFailed",
  "This browser cannot encode or play the media formats required for this call. Try the latest Chrome, Edge, or Safari.": "mediaFormatsUnsupported",
  "Video is unavailable in this browser. You can still join with audio.": "videoUnavailable",
  "Audio is unavailable in this browser. You can still join with video.": "audioUnavailable",
  "Safari support is experimental. The call may disconnect because WebTransport support is still being stabilized.": "safariExperimental",
};

export function translateSupportMessage(locale: Locale, message: string): string {
  let localized = message;
  for (const [source, key] of Object.entries(knownSupportMessages)) {
    if (!key) continue;
    localized = localized.replace(source, translate(locale, key));
  }
  return localized;
}
